-- =============================================================
-- 契約書に「法人名」の行を確実に入れる（本番で入っていなかったぶんの直し）
-- ---------------------------------------------------------------
--  20260906000000_contract_org.sql は、すでにある雛形に法人名の行を
--  足すとき、こう書いていました。
--
--      replace(body, '■ 契約者' || chr(10) || '  メールアドレス：…', …)
--
--  文字がひとつでも違えば、replace は何もしません。そして
--  「何もしなかった」ことを誰にも言いません。本番ではここが空振りし、
--  確認の数が 4 のはずが 2 になりました。
--
--  ■ これが実務で何を意味していたか
--    顧客契約は、同意のときに法人名（会社名）の記入を必須にしています。
--    ところが書面の側にその行が無いので、
--
--      記入していただいた会社名が、同意した書面のどこにも出ない
--
--    という状態でした。何を根拠に「その会社と契約した」と言うのか、
--    書面から読み取れません。契約書としていちばん困る抜けです。
--
--  ■ 直し方
--    目印を「■ 契約者 の見出しの行」だけにします。字下げや改行コード
--    （\r\n か \n か）に左右されないよう、正規表現で見出しの行末を
--    見つけ、その次の行に差し込みます。
--
--    そして確認では「入ったかどうか」ではなく
--    **「まだ入っていない雛形が何本あるか」** を数えます。0 でなければ
--    目で見て直していただく必要がある、と分かるようにするためです。
--
--  ※ すでに同意済みの契約には手を触れません。同意した瞬間の書面
--    （agreed_body）は動かさないのが、この仕組みの土台だからです。
--    ローンチ前で同意の実績が無ければ、実害はここで止まります。
--
--  確かめかた：入っていない雛形=0、公開中の雛形=5
--
-- 実行方法: Supabase Dashboard → SQL Editor に貼り付けて Run
--           何度流しても同じ結果になります。
-- =============================================================

-- ---------------------------------------------------------------
-- ① 会社として契約する区分（顧客・EP-I・EP-II本部）
-- ---------------------------------------------------------------
--  '■ 契約者' で始まる行を見つけ、その行のうしろに法人名の行を足す。
--  \r があっても行末として扱う
update public.contract_templates
   set body = regexp_replace(body,
        '(^[ \t]*■[ \t]*契約者[^\n]*\r?\n)',
        '\1  法人名：{{法人名}}' || chr(10),
        'n')                      -- 'n' … 行頭 ^ を各行で効かせる
 where kind in ('customer','partner_ep1','partner_ep2')
   and body !~ '\{\{法人名\}\}'
   and body ~ '(?n)^[ \t]*■[ \t]*契約者';

-- ---------------------------------------------------------------
-- ② 認定パートナー（個人）は屋号を任意で
-- ---------------------------------------------------------------
update public.contract_templates
   set body = regexp_replace(body,
        '(^[ \t]*■[ \t]*契約者[^\n]*\r?\n)',
        '\1  屋号・法人名（ある場合）：{{法人名}}' || chr(10),
        'n')
 where kind = 'partner'
   and body !~ '\{\{法人名\}\}'
   and body ~ '(?n)^[ \t]*■[ \t]*契約者';

-- ---------------------------------------------------------------
-- ③ 見出しが見つからなかった雛形の受け皿
-- ---------------------------------------------------------------
--  運営が本文を書き換えて「■ 契約者」を消している場合、①②は
--  空振りします。黙って通すと、また同じことが起きます。
--  差し込み先が分からない以上、勝手な場所に入れるべきではないので、
--  本文の最後に「記名欄」として付け足し、必ず書面に出るようにします。
update public.contract_templates
   set body = body || chr(10) || chr(10)
              || '■ 記名' || chr(10)
              || '  法人名：{{法人名}}' || chr(10)
 where kind in ('customer','partner','partner_ep1','partner_ep2')
   and body !~ '\{\{法人名\}\}';

-- ---------------------------------------------------------------
-- ④ 確かめ
-- ---------------------------------------------------------------
select
  --  ここが 0 でないと、記入いただいた会社名が書面に出ません
  (select count(*) from public.contract_templates
    where kind in ('customer','partner','partner_ep1','partner_ep2')
      and body !~ '\{\{法人名\}\}')                       as "入っていない雛形",
  (select count(*) from public.contract_templates
    where active)                                          as "公開中の雛形",
  (select count(*) from public.contract_templates
    where active and body ~ '\{\{法人名\}\}')              as "法人名が入っている公開中の雛形";
--  期待値：入っていない雛形=0、公開中の雛形=5、法人名が入っている公開中の雛形=4
--    （EP-II の所属パートナーは個人なので、法人名ではなく本部名が入ります）
