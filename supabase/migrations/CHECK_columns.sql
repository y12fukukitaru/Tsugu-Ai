select u.tbl as 表, u.col as 列,
       case
         when t.table_name is null then '❌ 表がありません'
         when c.column_name is null then '❌ 列がありません'
       end as 状態
  from used u
  left join information_schema.tables  t
    on t.table_schema='public' and t.table_name=u.tbl
  left join information_schema.columns c
    on c.table_schema='public' and c.table_name=u.tbl and c.column_name=u.col
 where t.table_name is null or c.column_name is null
 order by u.tbl, u.col;

