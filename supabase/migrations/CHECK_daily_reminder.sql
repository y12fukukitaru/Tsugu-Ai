-- =============================================================
-- daily-reminder は、動いているのか。動いて「送らなかった」のか。
-- ---------------------------------------------------------------
--  2026-09-02、届いたメールは 6:00 の週次ブリーフ（agent-heartbeat）だけで、
--  8:00 のメールは届かなかった。daily-reminder の定期実行は
--  23:00 UTC ＝ 8:00 JST に組まれているので、次のどちらかになる。
--
--    ① 動いたが、送る相手・送る用事が無かった（正常）
--    ② 動かなかった／途中で落ちた（要対応）
--
--  この2つは、届かなかったという事実だけでは区別がつかない。
--  下の3つを流すと、どちらなのかが分かる。
--
-- 実行方法: Supabase Dashboard → SQL Editor に貼り付けて Run
--           読み取るだけなので、何度実行しても何も変わらない。
-- =============================================================


-- ---------------------------------------------------------------
-- 1. 直近の実行履歴（動いたかどうか）
-- ---------------------------------------------------------------
--  succeeded が並んでいれば、呼び出し自体は成功している。つまり①寄り。
--  failed があれば、その 結果 の欄に理由が出る。
--  そもそも行が出てこなければ、定期実行が止まっている（②）。
select j.jobname                                as ジョブ名,
       d.start_time at time zone 'Asia/Tokyo'   as 実行時刻_日本時間,
       d.status                                 as 結果,
       left(coalesce(d.return_message,''), 200) as 内容
  from cron.job_run_details d
  join cron.job j using (jobid)
 where j.jobname in ('daily-reminder', 'agent-heartbeat-daily')
 order by d.start_time desc
 limit 20;


-- ---------------------------------------------------------------
-- 2. 呼び出しに対する応答（関数が中で落ちていないか）
-- ---------------------------------------------------------------
--  1 が succeeded でも、それは「HTTPで叩けた」という意味でしかない。
--  関数の中で落ちていれば、ここに 500 が出る。
--    200 → 関数は正常に終わった（＝送る用事が無かっただけ。①）
--    401 → 呼び出しの鍵が合っていない
--    500 → 関数の中で落ちている（②）
--  行が出なければ pg_net 経由ではないので、そのときは 3 を見る。
select r.created at time zone 'Asia/Tokyo' as 時刻_日本時間,
       r.status_code                       as 応答,
       q.url                               as 宛先,
       left(coalesce(r.error_msg, r.content, ''), 300) as 中身
  from net._http_response r
  join net.http_request_queue q using (id)
 where q.url ilike '%daily-reminder%'
 order by r.id desc
 limit 10;


-- ---------------------------------------------------------------
-- 3. そもそも、どう組まれているか
-- ---------------------------------------------------------------
--  active が false なら、止められているということ。
--  schedule が期待どおり '0 23 * * *' かどうかもここで確かめる。
select jobid,
       jobname  as ジョブ名,
       schedule as 時刻,
       active   as 動作中,
       left(command, 300) as 中身
  from cron.job
 where jobname ilike '%reminder%'
    or command ilike '%daily-reminder%'
 order by jobid;


-- =============================================================
-- 結果の読み方
-- ---------------------------------------------------------------
--  1 が succeeded ＋ 2 が 200
--      → 正常。今日は送る用事が無かっただけ。差出人名は
--        REMINDER_FROM か MAIL_FROM を読んでいるはずなので、
--        どちらも直っている以上、次に送られるときには
--        TsuguAi -継- になる。急いで直すものは無い。
--
--  1 が failed、または 2 が 500
--      → 関数が落ちている。Dashboard → Edge Functions →
--        daily-reminder → Logs に理由が出るので、それを貼って
--        教えてください。
--
--  1 に行が出ない、または 3 の 動作中 が false
--      → 定期実行が止まっている。9/12 のローンチまでに戻す必要がある。
--
--  いずれの場合も、daily-reminder の中身（Dashboard → Edge Functions →
--  daily-reminder → Code）を貼っていただければ、monthly-report と同じように
--  リポジトリに取り込んで、差出人名と件名を揃えます。いまはこの関数だけが
--  リポジトリの外にあり、こちらから中身を確かめられません。
-- =============================================================
