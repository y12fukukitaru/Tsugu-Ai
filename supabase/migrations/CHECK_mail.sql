--  いる仕掛けが、このリポジトリの中には見当たらない。つまり Supabase 側だけに
--  置かれている（ダッシュボードで直接書いた Edge Function か、pg_cron の
--  ジョブか、データベース関数のどれか）。
--
--  差出人名や件名を直すには、まずその居場所を確かめる必要がある。
--  下の3つを順に流して、結果を貼って教えてください。
--
-- 実行方法: Supabase Dashboard → SQL Editor に貼り付けて Run
--           読み取るだけなので、何度実行しても何も変わらない。
