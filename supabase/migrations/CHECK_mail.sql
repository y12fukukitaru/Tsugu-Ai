-- ---------------------------------------------------------------
-- 1. 定期実行の一覧（ここに月次のジョブがあるはず）
-- ---------------------------------------------------------------
--  schedule が '0 * 1 * *' のように「毎月1日」になっているものが目当て。
--  command に functions/v1/〇〇 と書いてあれば、その〇〇が送り主。
select jobid,
       jobname   as ジョブ名,
       schedule  as 時刻,
       active    as 動作中,
       command   as 中身
  from cron.job
 order by jobid;


-- ---------------------------------------------------------------
-- 2. データベース関数の中に、メール送信が書かれていないか
-- ---------------------------------------------------------------
--  Edge Function ではなく、SQL の関数から直接 Resend を叩いている場合に
--  ここへ出る。0件なら、送り主は Edge Function のほう。
select n.nspname as スキーマ,
       p.proname as 関数名
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname not in ('pg_catalog','information_schema')
   and (p.prosrc ilike '%resend%'
     or p.prosrc ilike '%運営%'
     or p.prosrc ilike '%月次レポート生成%')
 order by 1, 2;


-- ---------------------------------------------------------------
-- 3. 送信の履歴（直近の送信先が分かる）
-- ---------------------------------------------------------------
--  pg_net を使って送っている場合だけ出る。「関係がありません」と出たら
--  pg_net 経由ではないということなので、それはそれで手がかりになる。
--  headers は応答側（_http_response）と要求側（http_request_queue）の両方に
--  あるため、q. を付けて要求側だと明示する。付けないと ambiguous で止まる。
select q.id, r.created, q.url, left(coalesce(q.headers::text,''), 120) as 見出し
  from net._http_response r
  join net.http_request_queue q using (id)
 order by id desc
 limit 20;


