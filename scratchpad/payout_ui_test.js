// =============================================================
// 口座を「預かる」形に変えたあとの、画面の文言と道すじの試験
//
//  いちばん確かめたいのは、**約束と動きが食い違っていないこと**。
//  動きだけ変えて「消えます」と書いたままにするのが、
//  この変更でいちばんまずい形なので、そこを機械で見張る。
// =============================================================
const fs = require('fs');
const SRC = fs.readFileSync(__dirname + '/../index.html', 'utf8');

let n = 0, bad = [];
function is(name, got, want) {
  n++;
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g !== w) bad.push({ name, got: g, want: w });
}
function ok(name, cond) { is(name, !!cond, true); }
function no(name, cond) { is(name, !!cond, false); }

// =============================================================
// ① もう嘘になった文言が、どこにも残っていないこと
// =============================================================
no('「この画面から消えています」は残っていない', /すでにこの画面から消えています/.test(SRC));
no('「登録が済むと口座番号はここから消えます」は残っていない',
  /登録が済むと口座番号はここから消えます/.test(SRC));
no('「押した時点で…消えます」は残っていない',
  /押した時点で、口座番号・名義・支店はこのプラットホームから消えます/.test(SRC));
no('「もう表示できなくなります」は残っていない', /もう表示できなくなります/.test(SRC));
no('ボタンが「この情報を消す」のままではない', /銀行に登録しました（この情報を消す）/.test(SRC));
ok('登録直後の案内も「消えます」と言わない', !/口座番号はこの画面から消えます/.test(SRC));
no('確認のダイアログが「消えます」と言っていない',
  /OKを押すと、口座番号・名義・支店はこのプラットホームから消えます/.test(SRC));

// =============================================================
// ② 預かっていることを、はっきり書いていること
// =============================================================
ok('パートナーに「暗号化してお預かり」と伝えている',
  /暗号化してお預かりしています/.test(SRC));
ok('運営画面にも預かる旨が出ている',
  /口座情報は<b style="color:var\(--navy\);">暗号化してお預かりしています。<\/b>/.test(SRC));
ok('開いた記録が残ることは、これまでどおり書いてある',
  /開いたことは記録に残ります/.test(SRC));
ok('確認するまで振り込まないと書いてある',
  /押すまでは、その口座へのお振込みは行いません/.test(SRC));

// =============================================================
// ③ 消す道が、両側にあること
// =============================================================
//  預かると決めたなら、やめる道が要る。ご本人からも、運営からも
ok('ご本人が消すボタンがある', /onclick="payForget\(\)"/.test(SRC));
ok('ご本人の関数が forget_mine を呼ぶ', /payout_account_forget_mine/.test(SRC));
ok('運営が消すボタンがある', /onclick="payForgetAdm\(/.test(SRC));
ok('運営の関数は理由を求める',
  /payout_account_forget',\{ p_user:uid, p_reason:String\(why\) \}/.test(SRC));
ok('理由が空なら止める', /if\(!String\(why\)\.trim\(\)\)\{ alert\('理由をご記入ください。'\); return; \}/.test(SRC));
ok('消すと振り込めなくなると伝えている', /消すと報酬のお振込みができなくなります/.test(SRC));
ok('辞めた方の口座は消すよう運営に促している',
  /パートナーが辞められたときは/.test(SRC));

// =============================================================
// ④ 消したあとの見え方
// =============================================================
//  消したのに「運営が確認中」と出ると、待っても何も起きない
ok('held を見て分岐している', /var held=\(a && a\.held!==false\);/.test(SRC));
ok('消したあとの案内がある', /口座情報は<b>消してあります<\/b>/.test(SRC));
ok('消したあとは振り込めないと伝えている',
  /このままでは報酬をお振込みできません。<\/b>お振込みを再開するには/.test(SRC));
ok('消したあとは入力欄をそのまま出す', /if\(a && held && !PAY_FORM_OPEN\)\{/.test(SRC));

// =============================================================
// ⑤ 言葉の統一（受け取り → 確認）
// =============================================================
//  「受け取って消す」操作ではなくなったので、名前も変える。
//  古い名前が残っていると、画面ごとに言うことが違う
no('「受け取り待ち」は残っていない', /受け取り待ち/.test(SRC));
ok('「確認待ち」になっている', /口座 確認待ち/.test(SRC));
ok('見出しも「お振込先の確認」', /お振込先の確認'/.test(SRC));
ok('確認のボタンの文言', /確認しました（この口座へ振り込む）/.test(SRC));

// =============================================================
// ⑥ 版
// =============================================================
const build = (SRC.match(/var APP_BUILD='([^']+)'/) || [])[1];
const vj = JSON.parse(fs.readFileSync(__dirname + '/../version.json', 'utf8'));
is('版が version.json と同じ', vj.build, build);

// =============================================================
console.log(n + ' 件中 ' + (n - bad.length) + ' 件 合格、' + bad.length + ' 件 不合格');
bad.forEach(b => console.log('  × ' + b.name + '\n      実際: ' + b.got + '\n    あるべき: ' + b.want));
process.exit(bad.length ? 1 : 0);
