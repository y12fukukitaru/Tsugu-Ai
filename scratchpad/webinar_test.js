ok('継ナビくんの資料一覧に（運営だけ）', /\{ f:'webinar-partner\.html', i:'📡', n:'認定パートナー説明会（ウェビナー）'[^\n]*who:\{ admin:'' \}, sec:'pitch' \}/.test(SRC));

