const fs = require('fs');
const R = (f) => fs.readFileSync(__dirname + '/../' + f, 'utf8');
const SRC = R('index.html'), MANP = R('manual-partner.html'), MANA = R('manual-admin.html');
let n = 0, bad = [];
function ok(name, c) { n++; if (!c) bad.push(name); }
function slide(src, t) { const i = src.indexOf('<section class="slide" data-t="' + t + '"'); if (i < 0) return ''; return src.slice(i, src.indexOf('</section>', i)); }

const hk1 = slide(MANP, '本業と連携①');
ok('保険：事前の同意なく募集に使わない', /顧問先の事前の同意なく保険の募集に使わない/.test(hk1) && /非公開金融情報の授受制限/.test(hk1));
ok('保険：抱き合わせをしない', /顧問料を払う条件として保険の契約を求めることもできません/.test(hk1));
ok('保険：質問から探せる', /保険募集人として気をつけることは？/.test(hk1));
const ng = slide(MANP, 'やってはいけないこと');
ok('禁止行為に：財務情報の無断利用と抱き合わせ', /顧問の仕事で知った財務情報を、顧問先の事前の同意なく募集に使うこと/.test(ng) && /抱き合わせること/.test(ng));
const mt = slide(MANP, '今月の面談台本');
ok('面談：月1回を目安・議事録・未実施月の記録', /月1回を目安/.test(mt) && /実施日・方法（対面／オンライン）・出席者/.test(mt) && /メッセージで残して/.test(mt));
ok('面談：質問から探せる', /面談の記録はどう残す？/.test(mt));
ok('日々の運用：毎月に議事録', /<b>面談の議事録を残す<\/b>（実施日・方法・出席者。できなかった月はメッセージで記録）/.test(slide(MANP, '日々の運用')));
ok('「月1回以上」の言い方は使わない', !/月1回以上/.test(MANP) && !/月1回以上/.test(SRC));
const ex = slide(MANP, 'ご自身の契約を終えるとき');
ok('終了後：勧誘をしない・本業は別・資料の廃棄', /TsuguAi との顧問契約の解約を勧めたり、同じ種類の経営支援の契約を持ちかけたりしない/.test(ex) && /本業（有資格の業務）の取引は、この限りではありません/.test(ex) && /終了時に廃棄/.test(ex));
const px = slide(MANA, 'パートナーの契約の終了');
ok('運営：停止中を制裁に使わない・制裁の手順', /行動基準の違反への制裁には使わないでください/.test(px) && /是正を求める通知 → 【14】日の猶予 → 理由を書面で通知 → 異議の申立て/.test(px));
ok('運営：担当が変わる前に知らせる', /担当が変わる顧問先には、<b>変わる前に<\/b>運営からお知らせ/.test(px));
const ex2 = slide(MANA, '専門家名簿');
ok('運営：紹介料は見直し中', /紹介料の受け取りは見直し中です/.test(ex2) && /新しく紹介料を受け取る取り決めはしないでください/.test(ex2));
ok('継ナビくん（パートナー）', /保険募集人は、顧問の仕事で知った預金・借入・財務の情報を顧問先の事前の同意なく募集に使わない/.test(SRC) && /面談は月1回を目安に、毎回カルテの議事録に実施日・方法\(対面\/オンライン\)・出席者を残す/.test(SRC));
ok('継ナビくん（運営）', /「停止中」は引き継ぎのためのもので、制裁には使わない/.test(SRC) && /専門家から紹介料を受け取っていい？→見直し中/.test(SRC));

if (bad.length) { bad.forEach(b => console.log('NG', b)); console.log(n + ' checks, ' + bad.length + ' failed'); process.exit(1); }
console.log('ALL OK ' + n + ' checks, 0 failed');
