// =============================================================
// プロダクト説明（パートナー・経営者）の試験（2026-10-06）
//   ① パートナー：法人保険の壁（問題提起）→ 越え方（解決）→ あなたが描く未来
//   ② 書いてあることが、アプリにある（研修の章数・決算書の読み取り・面談台本・
//      商談練習・保険の棚卸し・退職金と株対策のシミュレーター）
//   ③ お金の数字はアプリの決まりから計算して一致、保証しない・0円の月を同じ頁に
//   ④ 決まりごと（非公開金融情報・抱き合わせ禁止・了承のうえで）を外さない
//   ⑤ 説明会・募集案内・運営キット・経営者向け資料にも同じ筋を通す
// =============================================================
const fs = require('fs');
const R = (f) => fs.readFileSync(__dirname + '/../' + f, 'utf8');
const SRC = R('index.html'), PP = R('pitch-partner.html'), WP = R('webinar-partner.html'), RP = R('recruit-partner.html');
const PC = R('pitch-customer.html'), KIT = R('docs/webinar-partner-kit.md');
let n = 0, bad = [];
function ok(name, c) { n++; if (!c) bad.push(name); }
const secs = (h) => h.split('<section class="slide').slice(1).map((s) => s.slice(0, s.indexOf('</section>')));
const slideOf = (h, t) => secs(h).find((s) => s.indexOf('data-t="' + t + '"') >= 0) || '';
const order = (h) => secs(h).map((s) => (s.match(/data-t="([^"]*)"/) || [])[1]);

// ① パートナー向け：問題 → 解決 → 未来
const P = order(PP);
const wall = slideOf(PP, '法人保険の壁'), over = slideOf(PP, '法人保険の壁の越え方'), fut = slideOf(PP, 'あなたが描く未来');
ok('並び：市場 → 法人保険の壁 → 越え方 → プロダクト', P.indexOf('法人保険の壁') === P.indexOf('市場') + 1 && P.indexOf('法人保険の壁の越え方') === P.indexOf('法人保険の壁') + 1 && P.indexOf('プロダクト') === P.indexOf('法人保険の壁の越え方') + 1);
ok('並び：あなたに残るもの → あなたが描く未来 → 画面で見る', P.indexOf('あなたが描く未来') === P.indexOf('あなたに残るもの') + 1 && P.indexOf('画面で見る') === P.indexOf('あなたが描く未来') + 1);
ok('問題提起：法人保険の提案、したくないですか？', /<h2>法人保険の提案、したくないですか？<\/h2>/.test(wall));
['何を学ぶか', 'どのセミナーか', '時間とお金', '決算書が読めない', '社長と何を話すか'].forEach((w) => {
  ok('壁：' + w, wall.indexOf('<div class="w-t">' + w + '</div>') >= 0);
  ok('越え方：' + w + ' に答える札', over.indexOf('>' + w + ' →</div>') >= 0);
});
ok('なぜハードルが高いか：商品ではなく経営の判断', /なぜ、ハードルが高いのか。/.test(wall) && /<b>「経営の判断」<\/b>/.test(wall) && /社長の隣で数字を話せる立場/.test(wall));
ok('未来：売り込む人から、毎月相談される人へ', /<h2>「売り込む人」から、「毎月、相談される人」へ<\/h2>/.test(fut) && ['いま', '最初の1社', '顧問先が増える', '承継まで伴走'].every((x) => fut.indexOf('<div class="n">' + x + '</div>') >= 0));
ok('どの頁にも話す内容・質問から探せる', [wall, over, fut].every((s) => /<div class="talk">/.test(s) && /data-q="/.test(s)));
ok('表紙の話す内容：保険の方には 問題 → 解決 → 未来', /<b>保険の方には<\/b>3つの問いの次に「法人保険の壁」「法人保険の壁の越え方」、最後の前に「あなたが描く未来」/.test(PP));

// ② 書いてあることが、アプリにある
ok('研修は全5章・必修10（アプリの知識と同じ）', /研修プログラム\(全5章。必修10レッスン＋発展のM&A講座8レッスン/.test(SRC) && /全5章・必修10レッスン/.test(over) && /全5章・必修10レッスン/.test(PP));
ok('古い「全4章」がパートナー向け資料に残っていない', ![PP, WP, RP].some((h) => /全4章/.test(h)));
ok('FA実務講座の中身（財務三表・正常収益力・企業価値評価）', /財務三表 → 正常収益力 → 企業価値評価/.test(SRC) && /財務三表・正常収益力・企業価値評価/.test(over));
ok('決算書は形式を問わずAIが読み取る', /試算表・決算書を読み取る経理アシスタントです。様式・書式は問わず/.test(SRC) && /形式は問いません/.test(over));
ok('面談台本：見せる数字3つ・問い3つ', /見せる数字（3つ）/.test(SRC) && /問い（3つ）/.test(SRC) && /見せる数字3つ・問い3つ/.test(over));
ok('商談練習の相手（継ナビくん）', /🎭 継ナビくんと商談練習/.test(SRC) && /社長役の商談練習の相手/.test(over));
ok('保険・固定費の棚卸し・役員退職金・事業承継と株対策のシミュレーター', /t:'保険・固定費の棚卸し'/.test(SRC) && /役員退職金シミュレーター/.test(SRC) && /事業承継・株対策シミュレーター/.test(SRC)
  && /<b>保険・固定費の棚卸し<\/b>/.test(over) && /<b>役員退職金<\/b>/.test(over) && /<b>事業承継・株対策<\/b>/.test(over));
ok('前払いなし（説明会の「ご負担」と同じ）', /先にお支払いいただくことはありません/.test(slideOf(WP, 'ご負担')) && /先にお支払いいただく費用はありません/.test(over));

// ③ お金の数字はアプリの決まりから
const STD = Number((SRC.match(/var EP_STD_FEE=(\d+);/) || [])[1]), SELL = Number((SRC.match(/var EP_SELLER_FEE=(\d+);/) || [])[1]);
const lv2 = /\{ lv:2, key:'Senior',[^\n]*need:\{cl:1,hd:0\}, fee:'50%' \}/.test(SRC), lv3 = /\{ lv:3, key:'Executive',[^\n]*fee:'60%'/.test(SRC);
const six = (STD * 3 + SELL * 3) * 0.5;
ok('例の金額：6社（買い手3・売り手3）×50% = 月120,000円', lv2 && six === 120000 && /月120,000円<\/b>（50%・税別）/.test(fut));
ok('レベル：最初の顧問契約で Lv.2（50%）、成約1件で Lv.3（60%）', lv2 && lv3 && /最初の顧問契約で<b>Lv.2（50%）<\/b>/.test(fut) && /成約1件で<b>Lv.3（60%）<\/b>/.test(fut));
ok('未来の頁に「保証しない・0円の月・差し引く前・運営が認定」', /収入を保証・約束するものではありません/.test(fut) && /担当先を得られない月は、報酬もご利用料も0円です/.test(fut) && /ご利用料・源泉徴収を差し引く前/.test(fut) && /率の適用とレベルの認定は運営が行います/.test(fut));
ok('法人保険の成約を約束しない（話す内容）', /「すぐ法人保険が売れるか」→ 約束しない/.test(over));

// ④ 決まりごと
const rules = (h) => /事前の同意なく募集に使わない/.test(h) && /抱き合わせ/.test(h);
ok('越え方の頁：立場の明示・非公開金融情報・抱き合わせ禁止', /顧問の立場と募集人の立場を<b>先に明示<\/b>/.test(over) && rules(over));
ok('提案は社長の了承を得てから・本業として', /<b>社長の了承を得てから<\/b>、あなたの本業として/.test(over) && /非公開金融情報の扱い（保険業法施行規則）/.test(over));
ok('アプリの知識と同じ決まり', /顧問先の事前の同意なく募集に使わない\(非公開金融情報の授受制限\)。顧問契約と保険の契約の抱き合わせもしない/.test(SRC));

// ⑤ ほかの資料にも同じ筋
const w = slideOf(WP, '法人保険の壁'), WO = order(WP);
ok('説明会：あなたの役割 → 法人保険の壁 → 保険・士業の方へ', WO.indexOf('法人保険の壁') === WO.indexOf('あなたの役割') + 1 && WO.indexOf('保険・士業の方へ') === WO.indexOf('法人保険の壁') + 1);
ok('説明会：5つの理由と5つの答え・了承のうえで・約束しない', /踏み出せない、5つの理由/.test(w) && (w.match(/<br>/g) || []).length === 8 && /<b>社長の了承のうえで<\/b>/.test(w) && /法人保険の成約や収入を約束するものではない/.test(w));
ok('説明会：流れの②に法人保険', /② 認定パートナーの役割（保険の方へ：法人保険の壁の越え方）と、1日の動き/.test(WP));
const r = slideOf(RP, '保険の方へ'), RO = order(RP);
ok('募集案内：なぜ、いま → 保険の方へ → あなたの役割', RO.indexOf('保険の方へ') === RO.indexOf('なぜ、いま') + 1 && RO.indexOf('あなたの役割') === RO.indexOf('保険の方へ') + 1);
ok('募集案内：決まりと「約束しない」', rules(r) && /法人保険の成約や収入を約束するものではありません/.test(r) && /<b>社長の了承のうえで<\/b>/.test(r));
ok('運営キット：告知の「こんな方へ」と弁護士の確認事項', /法人保険の提案をしたいのに、決算書の読み方や社長との話し方に自信がない方/.test(KIT) && /「法人保険の壁」の頁（法人保険の成約が増えると受け取られない書き方か）/.test(KIT));
const prom = slideOf(PC, '約束すること・しないこと');
ok('経営者向け：担当の本業（保険など）を押し付けない', /✔ 担当の本業（保険など）を押し付けない（ご了承なく財務の情報を使わず、抱き合わせもしない）/.test(prom) && /保険を売り込まれない？/.test(prom) && /<b>担当が保険の方なら<\/b>/.test(prom));

if (bad.length) { bad.forEach((b) => console.log('NG ' + b)); console.log(n + ' checks, ' + bad.length + ' failed'); process.exit(1); }
console.log('ALL OK ' + n + ' checks, 0 failed');
