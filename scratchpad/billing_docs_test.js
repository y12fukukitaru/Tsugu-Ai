const fs = require('fs');
const R = (f) => fs.readFileSync(__dirname + '/../' + f, 'utf8');
let n = 0, bad = [];
function ok(name, c) { n++; if (!c) bad.push(name); }
const SRC = R('index.html');
const MA = R('manual-admin.html'), MC = R('manual-customer.html'), MB = R('manual-buyer.html'), MS = R('manual-seller.html'), MP = R('manual-partner.html'), SEC = R('security.html');

//  画面の並び：ご請求の案内 → ご契約について（説明書はこの順で書く）
ok('画面：ご請求の案内が「ご契約について」より上', SRC.indexOf("'<div id=\"my-unpaid\"></div>'") < SRC.indexOf("'<div id=\"my-contract\"></div>'"));
ok('経営者：決済リンクの記述が残っていない（買い手版・売り手版も）', [MC, MB, MS].every((m) => !/決済リンク/.test(m)));
ok('経営者：お支払いの画面の並び（これからのお支払い → ご契約について → 記録）', /いちばん上に<b>これからのお支払い<\/b>/.test(MC) && /カードでのお支払いはありません。/.test(MC));
ok('経営者：お支払いのメール4種となりすましの注意', /<tr><th>お支払いのメール<\/th>/.test(MC) && /初回のお振込みのご案内/.test(MC) && /<b>請求書<\/b>（銀行振込の月の顧問料など）/.test(MC) && /ご利用の一時停止のお知らせ/.test(MC) && /メールだけでお振込先の変更をお願いすることはありません。/.test(MC));
ok('パートナー：請求書は運営から社長のメールへ', /<b>請求書は運営から<\/b>社長の登録のメールへ届きます/.test(MP));
ok('運営：月次の締めに請求書メールと督促', /<b>請求を立て、請求書を送る<\/b>/.test(MA) && /<b>入金と突き合わせ、未収を追う<\/b>/.test(MA));
ok('運営：自動の通知にお支払いのメール', /<tr><th>お支払い<br>（経営者・担当）<\/th>/.test(MA) && /毎朝9時に確かめ/.test(MA));
ok('運営：課金の全体像（発行者・請求書メール・お振込みのお願い・一時停止）', /<b>請求書の発行者<\/b>、総合振込/.test(MA) && /→ <b>請求書をメールで送る<\/b> →/.test(MA) && /翌月1日からご利用を一時停止/.test(MA));
ok('運営：全体像の課金・契約', /請求と未収（<b>請求書メール・お振込みのお願い・口座振替の手続き<\/b>）/.test(MA));
ok('情報の守り：お支払いのメールは宛名・金額を載せる（登録のアドレスへだけ）', /<b>お支払いのメールは別です。<\/b>/.test(SEC) && /登録のメールアドレスへだけ/.test(SEC) && /お支払いのメール（請求書など）だけは/.test(SEC));
ok('情報の守り：お客様の口座振替の口座は置かない', /<b>お客様の口座振替の口座（口座番号・名義・届出印）も置きません<\/b>/.test(SEC));
ok('情報の守り：ご請求とお支払いの記録を見られる人', /<tr><th>ご請求とお支払いの記録<\/th><td>ご本人／担当パートナー／運営/.test(SEC));

if (bad.length) { console.log('FAILED', bad.length, 'of', n); bad.forEach((b) => console.log(' ✗', b)); process.exit(1); }
console.log('ALL OK', n, 'checks, 0 failed');
