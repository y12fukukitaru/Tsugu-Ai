// =============================================================
// 継ナビくんの仕様の試験（ローンチ前の確認）
//
//  いちばん確かめたいのは「役割ごとに、正しいことを言うか」。
//  持っていない画面の名前を案内されると、探しに行って見つからず、
//  その方は継ナビくんを信用しなくなります。
// =============================================================
const fs = require('fs');
const SRC = fs.readFileSync(__dirname + '/../index.html', 'utf8');

let n = 0, bad = [];
function is(name, got, want) {
  n++;
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g !== w) bad.push({ name, got: g, want: w });
}
function ok(name, cond) { is(name, !!cond, true); }
function no(name, cond) { is(name, !!cond, false); }

function takeFn(name) {
  const re = new RegExp('\\n  function ' + name + '\\s*\\(', 'g');
  let m, last = null;
  while ((m = re.exec(SRC)) !== null) last = m;
  if (!last) throw new Error('見つかりません: ' + name);
  const end = SRC.indexOf('\n  }\n', last.index);
  if (end < 0) throw new Error('終わりが見つかりません: ' + name);
  return SRC.slice(last.index, end + 4);
}

//  役割を差し替えられるようにして、案内文を組み立てさせる
function guideFor(role) {
  const mod = new Function(
    'var __r=' + JSON.stringify(role) + ';' +
    'function aisecPortal(){ return __r; }' +
    takeFn('secUsageGuide') +
    'return secUsageGuide();'
  );
  return mod();
}

const gAdmin = guideFor('admin');
const gPartner = guideFor('consultant');
const gCustomer = guideFor('customer');

// =============================================================
// ① 運営に、運営の画面を案内する
// =============================================================
//  ここが壊れていました。運営は else に落ちて、経営者ダッシュボードの
//  画面ガイドを渡されていた
ok('運営には運営コンソールの案内', /【運営コンソールの画面ガイド】/.test(gAdmin));
no('運営に経営者の画面ガイドを渡さない', /【経営者ダッシュボードの画面ガイド】/.test(gAdmin));
no('運営にパートナーの画面ガイドを渡さない', /【パートナーポータルの画面ガイド】/.test(gAdmin));
//  運営の画面に無いものを、あるように言わない
no('運営に「月次レポート」と言わない', /月次レポート=/.test(gAdmin));
no('運営に「財務・資金繰り」と言わない', /財務・資金繰り=/.test(gAdmin));
no('運営に「成長・研修」と言わない', /成長・研修=/.test(gAdmin));
//  聞いているのが運営なので、「運営サポートへ」は行き先が無い。
//  知らないことは知らないと言うほうが親切
no('運営を「運営サポートへ」と回さない', /運営サポートへ」と案内します/.test(gAdmin));
ok('運営には分かりかねると正直に言わせる',
  /その機能はこちらでは分かりかねます/.test(gAdmin));
ok('パートナーはこれまでどおり運営サポートへ', /運営サポートへ」と案内します/.test(gPartner));
ok('経営者もこれまでどおり', /運営サポートへ」と案内します/.test(gCustomer));

// =============================================================
// ② いま使う画面が、案内に入っていること
// =============================================================
ok('契約書の送付先を案内できる', /サポート管理」の📄契約/.test(gAdmin));
ok('契約の種類を選ぶ必要を伝える', /種類（認定パートナー／EP-I／EP-II本部／EP-II所属）を選ばないと送れません/.test(gAdmin));
ok('月次の請求の立て方を案内できる', /この月の請求を立てる/.test(gAdmin));
ok('単発の請求を案内できる', /単発の請求/.test(gAdmin));
ok('顧問料は単発で立てられないと伝える', /顧問料はここでは立てられません/.test(gAdmin));
ok('お振込先の確認の場所を案内できる', /お振込先の確認/.test(gAdmin));
ok('サポート管理に契約があると書いてある', /契約書の送付（パートナー契約はここから送ります）/.test(gAdmin));

// =============================================================
// ③ 運営に無いタブを、あるように言わない
// =============================================================
//  メッセージとナレッジのタブは、運営では隠してある
ok('運営にメッセージ・ナレッジが無いと伝える',
  /運営にメッセージタブとナレッジタブはありません/.test(gAdmin));
ok('タブを隠す実装がある（メッセージ）',
  /var mt=\$\('knv-tab-msg'\); if\(mt\) mt\.classList\.toggle\('hidden', \(window\.__eff\|\|''\)==='admin'\);/.test(SRC));
ok('タブを隠す実装がある（ナレッジ）',
  /var kt=\$\('knv-tab-kn'\); if\(kt\) kt\.classList\.toggle\('hidden', \(window\.__eff\|\|''\)!=='consultant'\);/.test(SRC));
//  ボタンを隠すだけでなく、開かれても中身に行かせない
ok('運営がメッセージを開いても相談に戻す',
  /if\(t==='msg' && \(window\.__eff\|\|''\)==='admin'\) t='chat';/.test(SRC));
ok('パートナー以外がナレッジを開いても相談に戻す',
  /if\(t==='kn' && \(window\.__eff\|\|''\)!=='consultant'\) t='chat';/.test(SRC));

// =============================================================
// ④ ほかの役割は、これまでどおり
// =============================================================
ok('パートナーにはパートナーの案内', /【パートナーポータルの画面ガイド】/.test(gPartner));
ok('経営者には経営者の案内', /【経営者ダッシュボードの画面ガイド】/.test(gCustomer));
no('経営者にパートナーの案内を渡さない', /【パートナーポータルの画面ガイド】/.test(gCustomer));
//  経営者に数字の入力を求めない、という約束は残っているか
ok('経営者に試算表の入力を求めない約束が残っている',
  /経営者に試算表など月次の数字の入力を求めない/.test(gCustomer));

// =============================================================
// ⑤ 推測で答えさせない
// =============================================================
ok('ガイドに無い機能は推測で説明しない',
  /ガイドにない機能は推測で説明せず/.test(gAdmin));
ok('不確実なことを確からしく語らない', /不確実なことを、確からしく語らないでください。/.test(SRC));
ok('専門家の確認を促す分野が決めてある',
  /税額・申告の具体的判断は税理士、就業規則や社会保険の個別判断は社労士/.test(SRC));

// =============================================================
// ⑥ 版
// =============================================================
const build = (SRC.match(/var APP_BUILD='([^']+)'/) || [])[1];
const vj = JSON.parse(fs.readFileSync(__dirname + '/../version.json', 'utf8'));
is('版が version.json と同じ', vj.build, build);

// =============================================================
console.log(n + ' 件中 ' + (n - bad.length) + ' 件 合格、' + bad.length + ' 件 不合格');
bad.forEach(b => console.log('  × ' + b.name + '\n      実際: ' + b.got + '\n    あるべき: ' + b.want));
process.exit(bad.length ? 1 : 0);
